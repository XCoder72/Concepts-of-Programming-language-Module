"""Assignment Operators
Assign values to variables.
Operator
=	x = 5	Assign
+=	x += 2	Add and Assign
-=	x -= 2	Subtract and Assign
*=	x *= 2	Multiply and Assign
/=	x /= 2	Divide and Assign
%=	x %= 2	Modulus and Assign """

a = 10
print(a)
a += 5  # a = a + 5
print(a)
a -= 3 # a = a - 3
print(a)
a *= 2 # a = a * 2
print(a)
a /= 4 # a = a / 4
print(a)
a %= 2 # a = a % 2
print(a)