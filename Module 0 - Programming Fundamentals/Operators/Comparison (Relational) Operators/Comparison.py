"""Comparison (Relational) Operators
Compare two values.
The result is always True/False (Python).
Operator
==	Equal
!=	Not Equal
>	Greater Than
<	Less Than
>=	Greater Than or Equal
<=	Less Than or Equal
"""

a = 10
print(a == 10)  # Output: True
print(a != 10)  # Output: False
print(a > 10)   # Output: False
print(a < 10)   # Output: False
print(a >= 10)  # Output: True 
print(a <= 10)  # Output: True
