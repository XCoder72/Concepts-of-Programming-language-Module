""" Newline - A newline moves the cursor to the next line.
*\n - include in "".
* print() - automatically adds a newline.
* end="" - remain at same line.
* sep="" - controls the spacing between multiple values.
"""

# without end="",sep="",print(),\n
print("hello World !")
# with Print()
print("hey Buddy")
print("Welcome To Python")
print()
# with \n
print("hey Buddy\nWelcome To Python")
print()
# with end=""
print("hey Budddy",end="")
print("Welcome To Python")
# with sep=""
print("hey Budddy","Welcome To Python",sep="-")

