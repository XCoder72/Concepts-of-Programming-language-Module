# Python (Dynamic Typing)
# Python automatically detects that which datatype use for variable.

# variable declaration & initialization
var = 10

print("The value of var is:", var)

# Variable Assignment  - assigning a new value to an existing variable.
var = 20
        
print("The value of var is:", var)

""" python is Dynamic Typing Language, so we can assign any datatypes value
 to a variable """

var = "Hello"
print("The value of var is:", var)

# Declaration and initialization happen together.

# declaration and initialization of multiple variables in a single line.
var1, var2, var3 = 10, 20.5, "Hello"
print("The value of var1 is:", var1)
print("The value of var2 is:", var2)
print("The value of var3 is:", var3)