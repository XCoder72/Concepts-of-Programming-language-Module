// C++ program to create variables for a bank account (account holder, balance, account number) and print all details.

#include <iostream>
using namespace std;

int main() {
    // Create variables for a bank account (account holder, balance, account number)
    string accountHolder = "Rahul Verma";
    int balance = 1000;
    string accountNumber = "123456789";

    // Print all details
    cout << "Account Holder: " << accountHolder << endl;
    cout << "Balance: " << balance << endl;
    cout << "Account Number: " << accountNumber << endl;

    return 0;
}