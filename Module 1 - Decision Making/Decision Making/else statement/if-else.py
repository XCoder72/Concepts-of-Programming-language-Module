""" The if-else statement executes one block 
if the condition is true, 
otherwise it executes another block. """

"""
if condition:
    statement1
else:
    statement2
"""

# Example 1
age = 20

if age >= 18:
    print("Eligible to Vote")
else:
    print("Not Eligible to Vote")

# Example 2
marks = 35

if marks >= 40:
    print("Pass")
else:
    print("Fail")